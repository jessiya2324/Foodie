export const findFood = (foodId) => {
  for (const restaurant of restaurants) {
    const food = restaurant.menu.find((item) => item.id === foodId);
    if (food) return { ...food, restaurant };
  }
  return null;
};

export const allFoods = restaurants.flatMap((restaurant) =>
  restaurant.menu.map((food) => ({ ...food, restaurant })),
);
